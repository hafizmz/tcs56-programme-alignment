    'Programme', 'Example 5 - BSc Physics with Medical Physics (UK credits)', ...
    'CreditRequirement', 360, 'CreditFactor', 0.25, 'CompareWith', 'B.6', ...
    'OutDir', fullfile(out, 'ex5'));

